import { useCallback, useEffect, useState } from "react";
import { useNavigate, useParams } from "react-router-dom";
import {
    ArrowLeft, Star, Archive, ArchiveRestore, CornerUpLeft, UserCheck, CheckCircle2,
    Sparkles, PenLine, Send, MoreHorizontal, Paperclip,
} from "lucide-react";
import { toast } from "sonner";
import { Avatar, PriorityBadge, RespBadge, AIBadge, Empty } from "@/components/bits";
import { DropdownMenu, DropdownMenuContent, DropdownMenuItem, DropdownMenuTrigger } from "@/components/ui/dropdown-menu";
import { Skeleton } from "@/components/ui/skeleton";
import { useUI } from "@/lib/ui";
import api, { sse } from "@/lib/api";
import { fullDate, clockTime, dayTime, initialsOf, tintOf, deadlineLabel } from "@/lib/format";
import { cn } from "@/lib/utils";
import { Button } from "@/components/ui/button";
import { Textarea } from "@/components/ui/textarea";

const RESP_OPTIONS = [
    { value: "assistant", label: "Assistant to reply", icon: CornerUpLeft },
    { value: "client", label: "Client to reply", icon: UserCheck },
    { value: "none", label: "No reply needed", icon: CheckCircle2 },
];

function AISection({ doc, variant, onAskAssistant }) {
    return (
        <section
            data-testid="ai-analysis-section"
            className="ai-tint rounded-2xl border ai-border p-4 md:p-5"
        >
            <div className="flex items-center justify-between gap-2 flex-wrap">
                <span className="inline-flex items-center gap-1.5 text-xs font-bold text-brand-dark">
                    <Sparkles size={14} />
                    AI Analysis
                </span>
                <AIBadge label="Generated by Pilot — not the sender" />
            </div>

            <div className="mt-3 grid gap-3 md:grid-cols-2">
                <div className="rounded-xl bg-white/80 border border-brand-border p-3">
                    <p className="text-[10px] font-bold uppercase tracking-[0.12em] text-slate-400">Summary</p>
                    <p className="mt-1 text-[13px] leading-relaxed text-slate-700">{doc.ai_summary || "—"}</p>
                </div>
                <div className="rounded-xl bg-white/80 border border-brand-border p-3">
                    <p className="text-[10px] font-bold uppercase tracking-[0.12em] text-slate-400">Why this classification</p>
                    <p className="mt-1 text-[13px] leading-relaxed text-slate-700">{doc.classification_reason || "—"}</p>
                </div>
            </div>

            <div className="mt-3 flex flex-wrap items-center gap-2">
                {doc.priority && <PriorityBadge priority={doc.priority} small />}
                <RespBadge responsibility={doc.responsibility} small />
                {doc.deadline && (
                    <span
                        data-testid="deadline-chip"
                        className="inline-flex items-center gap-1.5 rounded-full border border-red-100 bg-red-50 px-2.5 py-1 text-xs font-semibold text-red-600"
                    >
                        Deadline · {deadlineLabel(doc)}
                    </span>
                )}
                {doc.meeting && (
                    <span className="inline-flex items-center gap-1.5 rounded-full border border-sky-100 bg-sky-50 px-2.5 py-1 text-xs font-semibold text-sky-700">
                        {doc.meeting.title} · {fullDate(doc.meeting.start)}
                    </span>
                )}
            </div>

            {doc.action_items?.length > 0 && (
                <div className="mt-3 rounded-xl bg-white/80 border border-brand-border p-3">
                    <p className="text-[10px] font-bold uppercase tracking-[0.12em] text-slate-400">Action items</p>
                    <ul className="mt-1.5 space-y-1.5">
                        {doc.action_items.map((a, i) => (
                            <li key={i} className="flex items-start gap-2 text-[13px] text-slate-700">
                                <span className="mt-1 h-1.5 w-1.5 shrink-0 rounded-full bg-brand" />
                                {a}
                            </li>
                        ))}
                    </ul>
                </div>
            )}

            {variant === "client" && (
                <Button
                    data-testid="ask-assistant-handle-btn"
                    onClick={onAskAssistant}
                    className="mt-4 w-full h-11 rounded-xl bg-brand hover:bg-brand-dark text-white text-sm font-bold shadow-soft"
                >
                    <CornerUpLeft size={16} className="mr-2" />
                    Ask Assistant to Handle
                </Button>
            )}
        </section>
    );
}

export default function ConversationView({ emailId, variant = "assistant", onBack = null, onHandled = null }) {
    const [doc, setDoc] = useState(null);
    const [notFound, setNotFound] = useState(false);
    const [showAll, setShowAll] = useState(false);
    const [reply, setReply] = useState("");
    const [drafting, setDrafting] = useState(false);
    const [sending, setSending] = useState(false);
    const [draftSource, setDraftSource] = useState("");
    const { openAssistant } = useUI();
    const navigate = useNavigate();

    const load = useCallback(() => {
        api.get(`/emails/${emailId}`)
            .then((d) => setDoc(d.data))
            .catch(() => setNotFound(true));
    }, [emailId]);

    useEffect(() => {
        setDoc(null);
        setNotFound(false);
        setShowAll(false);
        setReply("");
        load();
    }, [load]);

    const patch = async (patchBody) => {
        const { data } = await api.patch(`/emails/${emailId}`, patchBody);
        setDoc(data);
    };

    const sendReply = async () => {
        if (!reply.trim() || sending) return;
        setSending(true);
        try {
            const { data } = await api.post(`/emails/${emailId}/reply`, { body: reply });
            setDoc(data);
            setReply("");
            toast.success("Reply sent");
        } catch (e) {
            toast.error("Could not send the reply. Try again.");
        } finally {
            setSending(false);
        }
    };

    const draftReply = async () => {
        if (drafting) return;
        setDrafting(true);
        setReply("");
        setDraftSource("pilot");
        await sse(
            "/assistant/draft",
            { email_id: emailId },
            {
                onDelta: (d) => setReply((r) => r + d),
                onError: (err) => toast.error(err),
            },
        );
        setDrafting(false);
    };

    const askAssistantToHandle = async () => {
        try {
            await api.patch(`/emails/${emailId}`, { responsibility: "assistant", handled: true });
            toast.success("Pilot will handle this conversation from here.");
            onHandled?.();
            if (variant === "client") navigate("/client");
        } catch {
            toast.error("Could not delegate. Try again.");
        }
    };

    if (notFound) return <Empty icon={Paperclip} title="Conversation not found" hint="It may have been removed." />;
    if (!doc) {
        return (
            <div className="space-y-3 p-5" data-testid="conversation-loading">
                <Skeleton className="h-7 w-2/3" />
                <Skeleton className="h-4 w-1/3" />
                <Skeleton className="h-24 w-full" />
                <Skeleton className="h-24 w-full" />
            </div>
        );
    }

    const visibleMessages = showAll ? doc.messages : doc.messages.slice(-2);

    return (
        <div className="flex h-full min-h-0 flex-col" data-testid="conversation-view">
            <div className="border-b border-slate-200/80 px-4 md:px-6 py-3 flex items-center gap-2">
                {onBack && (
                    <button
                        data-testid="conv-back-btn"
                        onClick={onBack}
                        className="flex h-9 w-9 items-center justify-center rounded-lg text-slate-500 hover:bg-slate-100"
                    >
                        <ArrowLeft size={18} />
                    </button>
                )}
                <div className="min-w-0 flex-1">
                    <h2 className="truncate text-[15px] md:text-base font-bold tracking-tight text-ink-900" data-testid="conv-subject">
                        {doc.subject}
                    </h2>
                    <p className="text-[11px] text-slate-400">
                        {doc.messages.length} message{doc.messages.length > 1 ? "s" : ""} · {variant === "client" ? "Private to you" : doc.sender_email}
                    </p>
                </div>
                <div className="flex items-center gap-1">
                    <button
                        data-testid="conv-star-btn"
                        onClick={() => patch({ starred: !doc.starred })}
                        className={cn(
                            "flex h-8 w-8 items-center justify-center rounded-lg transition-colors",
                            doc.starred ? "text-amber-500" : "text-slate-400 hover:bg-slate-100 hover:text-amber-500",
                        )}
                        title="Star"
                    >
                        <Star size={16} fill={doc.starred ? "currentColor" : "none"} />
                    </button>
                    {variant === "assistant" && (
                        <>
                            <button
                                data-testid="conv-archive-btn"
                                onClick={() => patch({ archived: !doc.archived })}
                                className="flex h-8 w-8 items-center justify-center rounded-lg text-slate-400 hover:bg-slate-100 hover:text-slate-600"
                                title={doc.archived ? "Restore" : "Archive"}
                            >
                                {doc.archived ? <ArchiveRestore size={16} /> : <Archive size={16} />}
                            </button>
                            <DropdownMenu>
                                <DropdownMenuTrigger asChild>
                                    <button
                                        data-testid="conv-resp-btn"
                                        className="flex h-8 items-center gap-1.5 rounded-lg border border-slate-200 px-2.5 text-xs font-semibold text-slate-600 hover:bg-slate-50"
                                    >
                                        <MoreHorizontal size={14} />
                                        Classify
                                    </button>
                                </DropdownMenuTrigger>
                                <DropdownMenuContent align="end">
                                    {RESP_OPTIONS.map((opt) => (
                                        <DropdownMenuItem
                                            key={opt.value}
                                            data-testid={`conv-resp-option-${opt.value}`}
                                            onClick={() => patch({ responsibility: opt.value })}
                                            className={cn("gap-2", doc.responsibility === opt.value && "bg-brand-soft text-brand-dark font-semibold")}
                                        >
                                            <opt.icon size={14} />
                                            {opt.label}
                                        </DropdownMenuItem>
                                    ))}
                                </DropdownMenuContent>
                            </DropdownMenu>
                            <button
                                data-testid="conv-ask-pilot-btn"
                                onClick={() => openAssistant({ id: doc.id, subject: doc.subject })}
                                className="flex h-8 items-center gap-1.5 rounded-lg bg-ink-900 px-2.5 text-xs font-semibold text-white hover:bg-ink-800"
                            >
                                <Sparkles size={13} className="text-brand" />
                                Ask Pilot
                            </button>
                        </>
                    )}
                </div>
            </div>

            <div className="flex-1 overflow-y-auto scrollbar-slim px-4 md:px-6 py-5 space-y-5">
                <AISection doc={doc} variant={variant} onAskAssistant={askAssistantToHandle} />

                <div className="space-y-4" data-testid="conv-thread">
                    {visibleMessages.map((m) => {
                        const mine = m.from_email === "daniel@northwindstudio.com";
                        return (
                            <article key={m.id} data-testid={`thread-msg-${m.id}`} className="card-base shadow-soft p-4 md:p-5">
                                <header className="flex items-center gap-3">
                                    <Avatar item={{ sender_name: m.from_name, tint: mine ? "slate" : doc.tint }} size={38} />
                                    <div className="min-w-0 flex-1">
                                        <p className="truncate text-sm font-bold text-ink-900">
                                            {m.from_name}
                                            {mine && <span className="ml-1.5 text-[10px] font-bold uppercase tracking-wide text-slate-400">you</span>}
                                        </p>
                                        <p className="truncate text-xs text-slate-400">{m.from_email}</p>
                                    </div>
                                    <time className="shrink-0 text-[11px] text-slate-400 font-mono-num">{dayTime(m.at)}</time>
                                </header>
                                <p className="mt-3 whitespace-pre-wrap text-[14px] leading-relaxed text-slate-700">{m.body}</p>
                            </article>
                        );
                    })}
                </div>

                {doc.messages.length > 2 && !showAll && (
                    <button
                        data-testid="show-earlier-btn"
                        onClick={() => setShowAll(true)}
                        className="mx-auto block rounded-full border border-slate-200 bg-white px-4 py-2 text-xs font-semibold text-slate-500 hover:text-ink-900 hover:border-slate-300"
                    >
                        View earlier messages ({doc.messages.length - 2})
                    </button>
                )}
            </div>

            <div className="border-t border-slate-200/80 bg-white p-4" data-testid="reply-composer">
                {draftSource === "pilot" && reply && (
                    <p className="mb-2 inline-flex items-center gap-1.5 rounded-md bg-brand-soft border border-brand-border px-2 py-1 text-[10px] font-bold uppercase tracking-wide text-brand-dark">
                        <Sparkles size={11} />
                        Drafted by Pilot — edit before sending
                    </p>
                )}
                <Textarea
                    data-testid="reply-textarea"
                    value={reply}
                    onChange={(e) => setReply(e.target.value)}
                    placeholder={`Reply to ${doc.sender_name}…`}
                    className="min-h-[88px] rounded-xl border-slate-200 bg-slate-50/60 text-sm focus:border-brand"
                />
                <div className="mt-2.5 flex items-center gap-2">
                    <Button
                        data-testid="reply-send-btn"
                        onClick={sendReply}
                        disabled={sending || !reply.trim()}
                        className="h-9 rounded-full bg-ink-900 hover:bg-ink-800 text-white text-sm font-semibold px-5"
                    >
                        <Send size={14} className="mr-2" />
                        {sending ? "Sending…" : "Send reply"}
                    </Button>
                    {variant === "assistant" && (
                        <Button
                            data-testid="draft-reply-btn"
                            onClick={draftReply}
                            disabled={drafting}
                            variant="outline"
                            className="h-9 rounded-full border-slate-200 text-sm font-semibold text-slate-600 hover:text-brand-dark hover:border-brand"
                        >
                            {drafting ? (
                                <span className="flex items-center gap-2">
                                    <span className="h-3 w-3 rounded-full border-2 border-brand border-t-transparent animate-spin" />
                                    Drafting…
                                </span>
                            ) : (
                                <>
                                    <PenLine size={14} className="mr-2 text-brand" />
                                    Draft with Pilot
                                </>
                            )}
                        </Button>
                    )}
                </div>
            </div>
        </div>
    );
}
